/** Pick a supported locale from browser preferences; English is the fallback. */
export function detectLocale(language?: string | null): Locale {
  return language?.toLowerCase().startsWith("es") ? "es" : "en";
}

/** Look up a translated string and interpolate named values. */
export function translate(locale: Locale, key: string, values: Interpolation = {}): string {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
